/**
 * Converts data/catalogue.csv into data/products.imported.ts (which replaces the sample catalogue).
 *   npm run catalogue:import                 # data/catalogue.csv
 *   npm run catalogue:import -- my.csv       # another file
 *   npm run catalogue:import -- --clear      # go back to the sample catalogue
 * Columns: see data/catalogue.template.csv and the README. Lists use "|" as the separator.
 */
import { readFileSync, writeFileSync } from "fs";
import { join } from "path";
import { csvToSeeds } from "../lib/catalogue-import";

const OUT = join(process.cwd(), "data/products.imported.ts");
const args = process.argv.slice(2);

const header = (body: string) => `import type { Seed } from "./seed";

/**
 * Generated by \`npm run catalogue:import\` from data/catalogue.csv. While this list is empty the sample
 * catalogue in data/products.ts is used. Do not edit by hand.
 */
export const importedSeeds: Seed[] = ${body};
`;

if (args.includes("--clear")) {
  writeFileSync(OUT, header("[]"));
  console.log("Cleared imported products. The sample catalogue is active again.");
  process.exit(0);
}

const file = args.find((a) => !a.startsWith("--")) ?? "data/catalogue.csv";
let text: string;
try { text = readFileSync(join(process.cwd(), file), "utf8"); } catch { console.error(`Cannot read ${file}.`); process.exit(1); }

const { seeds, errors } = csvToSeeds(text);
if (errors.length) {
  console.error(`\n${errors.length} problem(s) found in ${file}. Nothing was written.\n`);
  errors.forEach((e) => console.error(" - " + e));
  process.exit(1);
}
writeFileSync(OUT, header(JSON.stringify(seeds, null, 2)));
console.log(`Imported ${seeds.length} products into data/products.imported.ts.`);
console.log("Next: add the photos at the paths listed in each product's images (or <group>/<slug>-1.webp), run `npm run images:optimize`, then build.");
